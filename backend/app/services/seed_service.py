"""Demo data: build records from ``sample_data/`` and load them when the database is empty.

``build_seed_records`` is pure (no database), so the same records feed both the SQLite
bootstrap here and ``database/seed.sql`` (generated by ``scripts/generate_seed_sql.py``).
Ids are deterministic ``uuid5`` values so a re-run can never create duplicates.
"""

import json
import uuid
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

from app.core.config import get_settings
from app.core.database import session_scope
from app.repositories import (
    CustomerRepository,
    IncidentRepository,
    ProductRepository,
    ProfileRepository,
    SubscriptionRepository,
    SupportArticleRepository,
    TicketMessageRepository,
    TicketRepository,
    WorkspaceRepository,
)
from app.repositories.base import BaseRepository
from app.schemas.common import Category, Channel, Role, SenderType, TicketStatus

SEED_NAMESPACE = uuid.UUID("6f1c2f0e-5a3b-4d7e-9c21-0c10d0de5eed")
REPO_ROOT = Path(__file__).resolve().parents[3]

DEMO_USERS: tuple[dict[str, str], ...] = (
    {"key": "admin", "email": "admin@clouddesk.demo", "full_name": "Alex Admin", "role": "admin"},
    {"key": "sam", "email": "sam.agent@clouddesk.demo", "full_name": "Sam Agent", "role": "agent"},
    {"key": "vic", "email": "vic.viewer@clouddesk.demo", "full_name": "Vic Viewer", "role": "viewer"},
)

# Insert order respects foreign keys. The value is the repository that owns the table.
SEED_TABLES: dict[str, type[BaseRepository[Any]]] = {
    "profiles": ProfileRepository,
    "customers": CustomerRepository,
    "subscriptions": SubscriptionRepository,
    "workspaces": WorkspaceRepository,
    "products": ProductRepository,
    "support_articles": SupportArticleRepository,
    "incidents": IncidentRepository,
    "tickets": TicketRepository,
    "ticket_messages": TicketMessageRepository,
}

Records = dict[str, list[dict[str, Any]]]


def stable_id(kind: str, key: str) -> str:
    """Deterministic UUID text for a sample-data key."""
    return str(uuid.uuid5(SEED_NAMESPACE, f"{kind}:{key}"))


def resolve_data_dir(configured: str | None = None) -> Path:
    """``SAMPLE_DATA_DIR`` may be absolute, relative to the CWD, or relative to the repo root."""
    path = Path(configured or get_settings().sample_data_dir)
    if path.is_absolute():
        return path
    for base in (Path.cwd(), REPO_ROOT):
        if (base / path).is_dir():
            return base / path
    return REPO_ROOT / path


def _read_json(data_dir: Path, name: str) -> list[dict[str, Any]]:
    with (data_dir / name).open(encoding="utf-8") as handle:
        return json.load(handle)


def _dt(value: str | None) -> datetime | None:
    return datetime.fromisoformat(value) if value else None


def parse_front_matter(text: str) -> tuple[dict[str, Any], str]:
    """Split ``---`` YAML-style front matter (``key: value`` and ``tags: [a, b]``) from the body."""
    if not text.startswith("---"):
        return {}, text
    _, front, body = text.split("---", 2)
    meta: dict[str, Any] = {}
    for line in front.strip().splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key.strip()] = [item.strip() for item in value[1:-1].split(",") if item.strip()]
        else:
            meta[key.strip()] = value
    return meta, body.lstrip("\n")


def load_article_files(data_dir: Path) -> list[dict[str, Any]]:
    """Read ``knowledge_base/*.md`` into ``support_articles`` records."""
    articles = []
    for path in sorted((data_dir / "knowledge_base").glob("*.md")):
        meta, body = parse_front_matter(path.read_text(encoding="utf-8"))
        category = meta.get("category", Category.OTHER.value)
        if category not in {c.value for c in Category}:
            raise ValueError(f"{path.name}: unknown category {category!r}")
        articles.append(
            {
                "id": stable_id("article", path.stem),
                "slug": path.stem,
                "title": meta["title"],
                "category": category,
                "tags": meta.get("tags", []),
                "summary": meta.get("summary", ""),
                "body": body,
            }
        )
    return articles


def build_seed_records(data_dir: Path | None = None) -> Records:
    """Turn the sample files into table records, keyed by table name in insert order."""
    root = data_dir or resolve_data_dir()
    customers = _read_json(root, "customers.json")
    customer_by_key = {c["key"]: c for c in customers}
    workspaces = _read_json(root, "workspaces.json")
    tickets = _read_json(root, "tickets.json")

    records: Records = {name: [] for name in SEED_TABLES}

    for user in DEMO_USERS:
        records["profiles"].append(
            {
                "id": stable_id("profile", user["key"]),
                "email": user["email"],
                "full_name": user["full_name"],
                "role": Role(user["role"]).value,
            }
        )

    for c in customers:
        records["customers"].append(
            {
                "id": stable_id("customer", c["key"]),
                "email": c["email"],
                "name": c["name"],
                "company": c["company"],
                "plan": c["plan"],
                "status": c["status"],
                "timezone": c["timezone"],
            }
        )

    for s in _read_json(root, "subscriptions.json"):
        record = {k: v for k, v in s.items() if k != "customer"}
        record["id"] = stable_id("subscription", s["customer"])
        record["customer_id"] = stable_id("customer", s["customer"])
        record["renews_at"] = _dt(s.get("renews_at"))
        records["subscriptions"].append(record)

    for w in workspaces:
        record = {k: v for k, v in w.items() if k not in ("key", "customer")}
        record["id"] = stable_id("workspace", w["key"])
        record["customer_id"] = stable_id("customer", w["customer"])
        records["workspaces"].append(record)

    for p in _read_json(root, "products.json"):
        records["products"].append({"id": stable_id("product", p["sku"]), **p})

    records["support_articles"] = load_article_files(root)

    for i in _read_json(root, "incidents.json"):
        record = {k: v for k, v in i.items() if k != "key"}
        record["id"] = stable_id("incident", i["key"])
        record["started_at"] = _dt(i["started_at"])
        record["resolved_at"] = _dt(i.get("resolved_at"))
        records["incidents"].append(record)

    for t in tickets:
        created = _dt(t["created_at"])
        customer = customer_by_key[t["customer"]]
        Channel(t["channel"])  # fail loudly on a bad channel
        records["tickets"].append(
            {
                "id": stable_id("ticket", t["number"]),
                "number": t["number"],
                "customer_id": stable_id("customer", t["customer"]),
                "subject": t["subject"],
                "body": t["body"],
                "channel": t["channel"],
                "status": TicketStatus.NEW.value,
                "created_at": created,
                "updated_at": created,
            }
        )
        records["ticket_messages"].append(
            {
                "id": stable_id("message", t["number"]),
                "ticket_id": stable_id("ticket", t["number"]),
                "sender_type": SenderType.CUSTOMER.value,
                "sender_name": customer["name"],
                "body": t["body"],
                "is_internal": False,
                "created_at": created,
                "updated_at": created,
            }
        )
    return records


@dataclass
class BootstrapResult:
    loaded: bool
    counts: dict[str, int] = field(default_factory=dict)


async def bootstrap_demo_data(data_dir: Path | None = None) -> BootstrapResult:
    """Load the sample data when the database has no customers and no tickets.

    One transaction, so a failure leaves the database empty and the next start retries.
    A non-empty database is left alone, which is what makes a second startup a no-op.
    """
    async with session_scope() as session:
        if await CustomerRepository(session).count() or await TicketRepository(session).count():
            return BootstrapResult(loaded=False)
        records = build_seed_records(data_dir)
        counts: dict[str, int] = {}
        for table, repo_class in SEED_TABLES.items():
            counts[table] = await repo_class(session).add_many(records[table])
        return BootstrapResult(loaded=True, counts=counts)
